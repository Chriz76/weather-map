/**
 * Generates every raster icon (favicon PNG, PWA icons, Apple touch icon) from
 * `public/logo.svg`, which holds the plain glyph without any background.
 *
 * `favicon.svg` adapts to the browser theme (blue on light, white on dark chrome), which
 * only SVG favicons can do, so the raster variants cover the other surfaces:
 * - the 48 px favicon fallback stays transparent, because browsers without SVG favicon
 *   support draw it on a light tab strip,
 * - the 196 px favicon uses a white circle with an optically centred glyph, because the
 *   Android tab UI renders a raster favicon and ignores the SVG theme switch,
 * - OS surfaces (PWA `any` icons, Apple touch icon) use the brand plate with a white
 *   glyph, matching the installed app icon on Android,
 * - the maskable icon keeps the glyph inside the 80% safe zone, because Android
 *   crops maskable icons to a circle / squircle.
 *
 * sharp is NOT a project dependency. Install it on demand and run:
 *   npm install --no-save sharp
 *   node tools/generate-icons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

/** Measured bounding box of the glyph in the logo coordinate system. */
const GLYPH_BOX = { x: 3.67875, y: 4.51952, w: 25.02168, h: 24.84298 };

/** Brand color of the map (same value as `--weather-map-accent-blue`). */
const BRAND_COLOR = '#0077a4';

const PUBLIC_DIR = path.resolve('public');
const SOURCE_SVG = path.join(PUBLIC_DIR, 'logo.svg');

/** Returns a square viewBox centered on the glyph; `ratio` is the glyph share of the box. */
function squareBox(ratio) {
    const side = Math.max(GLYPH_BOX.w, GLYPH_BOX.h) / ratio;
    return {
        side,
        x: GLYPH_BOX.x + GLYPH_BOX.w / 2 - side / 2,
        y: GLYPH_BOX.y + GLYPH_BOX.h / 2 - side / 2
    };
}

function viewBoxOf(box) {
    return [box.x, box.y, box.side, box.side].map((value) => value.toFixed(3)).join(' ');
}

/**
 * Extracts the glyph markup from the root `<svg>` element.
 *
 * Only the glyph group is kept: the source file carries no background, and any markup
 * before the group (comments, a future plate) must not leak into the generated icons.
 */
function readGlyphMarkup() {
    const source = fs.readFileSync(SOURCE_SVG, 'utf8');
    const match = source.match(/<svg[^>]*>([\s\S]*)<\/svg>/i);
    if (!match) throw new Error('Unexpected logo.svg structure');

    const inner = match[1];
    const glyphStart = inner.indexOf('<g');
    if (glyphStart === -1) throw new Error('Unexpected logo.svg structure: no glyph group');

    return inner.slice(glyphStart);
}

function buildSvg(glyphMarkup, box, size, options) {
    const viewBox = viewBoxOf(box);
    const glyph = options.fill ? glyphMarkup.replaceAll(BRAND_COLOR, options.fill) : glyphMarkup;
    const centerX = box.x + box.side / 2;
    const centerY = box.y + box.side / 2;
    const radius = (box.side * (options.plateRadius ?? 0)).toFixed(3);

    let backdrop = '';
    if (options.shape === 'circle') {
        backdrop = `<circle cx="${centerX.toFixed(3)}" cy="${centerY.toFixed(3)}" r="${(box.side / 2).toFixed(3)}" fill="${options.background}"/>`;
    } else if (options.background) {
        backdrop = `<rect x="${box.x.toFixed(3)}" y="${box.y.toFixed(3)}" width="${box.side.toFixed(3)}" height="${box.side.toFixed(3)}" rx="${radius}" fill="${options.background}"/>`;
    }

    // `offsetShare` corrects the optical center: the glyph's mass sits left of its bounding
    // box, so a right nudge balances it inside the plate. Proportional to the plate side, so
    // every icon gets the same relative correction instead of a per-file magic number.
    const offset = (options.offsetShare ?? 0) * box.side;
    const body = offset
        ? `<g transform="translate(${offset.toFixed(3)} 0)">${glyph}</g>`
        : glyph;

    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${size}" height="${size}">${backdrop}${body}</svg>`;
}

/**
 * Writes the adaptive SVG favicon used by desktop browser chrome.
 *
 * The glyph lives only in `logo.svg`; this keeps a single copy of the artwork in the repo.
 * It is the one variant that needs its own colour switching, so it cannot be a PNG.
 */
function buildFaviconSvg(glyphMarkup, viewBoxSize) {
    const shift = (OPTICAL_SHIFT * viewBoxSize).toFixed(2);
    const glyph = glyphMarkup.replace(`fill="${BRAND_COLOR}"`, `class="favicon-glyph" fill="${BRAND_COLOR}"`);
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewBoxSize} ${viewBoxSize}" width="100%" height="100%">
  <!-- Generated by tools/generate-icons.mjs - do not edit by hand. -->
  <!-- No plate: the browser surface decides the colour. The small translate is the
       optical center correction, same constant as for the raster icons. -->
  <style>
    .favicon-glyph { fill: ${BRAND_COLOR}; }
    @media (prefers-color-scheme: dark) {
      .favicon-glyph { fill: #ffffff; }
    }
  </style>
  <g transform="translate(${shift} 0)">
    ${glyph.trim().replaceAll('\n', '\n    ')}
  </g>
</svg>
`;
}

async function writeIcon(glyphMarkup, file, box, size, options) {
    const svg = buildSvg(glyphMarkup, box, size, options);
    await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(path.join(PUBLIC_DIR, file));
    console.log(`generated ${file} (${size}x${size})`);
}

const glyphMarkup = readGlyphMarkup();

/** Corner radius as a share of the plate side; matches the installed app icon. */
const PLATE_RADIUS = 0.22;

/**
 * Optical centering offset as a share of the icon side, applied to every generated icon.
 * Measured: the glyph's area centroid lies 4.1 units left of its bounding-box center in the
 * 32 unit grid, i.e. roughly 13 % of the side at 80 %; 5 % reads as balanced without pushing
 * the flag tip towards the rim. Plate or not does not matter - the eye balances the
 * silhouette, not the frame.
 */
const OPTICAL_SHIFT = 0.05;

const webBox = squareBox(0.82);
const osBox = squareBox(0.8);
const maskableBox = squareBox(0.62);
const appleBox = squareBox(0.78);

// Small transparent icons: Chrome draws these where the favicon is shown at tab size.
// `favicon-32x32.png` mirrors PayPal's pp32.png, which is declared for both `icon` and
// `shortcut icon` so the small size wins on small surfaces. The optical shift applies here
// too - the silhouette is what the eye balances, plate or not - so the frame is slightly
// smaller (82 %) to keep a margin to the right edge after the shift.
// Theme-dependent color is a job for `favicon.svg`, not for a raster file.
await writeIcon(glyphMarkup, 'favicon-32x32.png', webBox, 32, { offsetShare: OPTICAL_SHIFT });
await writeIcon(glyphMarkup, 'favicon-48x48.png', webBox, 48, { offsetShare: OPTICAL_SHIFT });

// Same artwork for the SVG favicon: one source, one offset constant.
fs.writeFileSync(path.join(PUBLIC_DIR, 'favicon.svg'), buildFaviconSvg(glyphMarkup, 32));
console.log('generated favicon.svg (adaptive, 32 viewBox)');

// Large icon with a white plate, mirroring PayPal's pp196.png. Chrome picks it for the
// bigger favicon surfaces (shortcut chips, search suggestions), while the small surfaces
// keep using the transparent 32 px file.
await writeIcon(glyphMarkup, 'favicon-196x196.png', squareBox(0.66), 196, { shape: 'circle', background: '#ffffff', offsetShare: OPTICAL_SHIFT });

// OS surface: brand plate, white glyph - same look as the maskable launcher icon.
await writeIcon(glyphMarkup, 'icon-192.png', osBox, 192, { background: BRAND_COLOR, fill: '#ffffff', plateRadius: PLATE_RADIUS, offsetShare: OPTICAL_SHIFT });
await writeIcon(glyphMarkup, 'icon-512.png', osBox, 512, { background: BRAND_COLOR, fill: '#ffffff', plateRadius: PLATE_RADIUS, offsetShare: OPTICAL_SHIFT });

// Android adaptive icon: full-bleed background, glyph inside the 80% safe zone.
await writeIcon(glyphMarkup, 'icon-maskable-512.png', maskableBox, 512, { background: BRAND_COLOR, fill: '#ffffff', offsetShare: OPTICAL_SHIFT });

// iOS ignores transparency and rounds the corners itself, so this one stays opaque and square.
await writeIcon(glyphMarkup, 'apple-touch-icon.png', appleBox, 180, { background: BRAND_COLOR, fill: '#ffffff', offsetShare: OPTICAL_SHIFT });
